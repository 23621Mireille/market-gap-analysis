# ── Key Insight box ───────────────────────────────────────────────────────────
st.markdown("### Key Insight")
if len(blue_ocean) > 0:
    cat_bo_counts = blue_ocean["primary_category"].value_counts()
    cat_totals    = df_filtered["primary_category"].value_counts()
    gap_ratio     = cat_bo_counts / cat_totals.reindex(cat_bo_counts.index).fillna(1)
    filtered_gap  = gap_ratio[gap_ratio.index != OTHER]

    if len(filtered_gap) > 0:
        top_cat   = filtered_gap.idxmin()
        top_prods = blue_ocean[blue_ocean["primary_category"] == top_cat]
        avg_p     = top_prods["proteins_100g"].mean()
        avg_s     = top_prods["sugars_100g"].mean()
        gap_pct   = (1 - gap_ratio[top_cat]) * 100

        st.info(
            f"Based on the data, the biggest market opportunity is in **{top_cat}**, "
            f"specifically targeting products with **{avg_p:.0f}g of protein** "
            f"and less than **{avg_s:.0f}g of sugar**. "
            f"Currently {gap_pct:.0f}% of {top_cat} products do NOT meet Blue Ocean "
            f"criteria — a large under-served segment for health-focused innovation."
        )
    else:
        st.info("All Blue Ocean products fall in the 'Other' category. Try broadening your filters.")
else:
    st.warning("No Blue Ocean products visible with current filters. Try relaxing the sliders.")

