# ── Constants (must match notebook) ──────────────────────────────────────────
DATA_URL = "https://static.openfoodfacts.org/data/en.openfoodfacts.org.products.csv.gz"
RELEVANT_COLS = [
    "product_name", "categories_tags",
    "sugars_100g", "proteins_100g",
    "fat_100g", "fiber_100g",
    "energy_100g", "ingredients_text",
]
PROTEIN_THRESHOLD = 10.0
SUGAR_THRESHOLD   = 5.0
PLOT_SAMPLE       = 30_000  # lower than notebook for web rendering

CATEGORY_MAP = {
    "Snacks & Crisps":     ["snack", "crisp", "chip", "popcorn", "pretzel", "cracker"],
    "Baked Goods":         ["biscuit", "cake", "cookie", "bread", "pastry", "wafer", "muffin", "brownie"],
    "Dairy & Eggs":        ["dairy", "cheese", "yogurt", "yoghurt", "milk", "egg", "cream"],
    "Beverages":           ["beverage", "drink", "juice", "water", "soda", "smoothie", "tea", "coffee"],
    "Protein Foods":       ["protein", "meat", "fish", "chicken", "beef", "whey", "bar", "shake"],
    "Confectionery":       ["chocolate", "candy", "sweet", "sugar", "caramel", "gum", "lolly"],
    "Cereals & Grains":    ["cereal", "granola", "oat", "grain", "muesli", "porridge", "rice"],
    "Fruits & Vegetables": ["fruit", "vegetable", "nut", "seed", "dried", "berry"],
    "Prepared & Packaged": ["prepared", "canned", "frozen", "instant", "soup", "sauce",
                            "condiment", "spread", "pasta", "noodle", "meal", "salad",
                            "seasoning", "dressing", "jam", "honey", "syrup"],
}
OTHER = "Other"

PROTEIN_KEYWORDS = [
    "whey", "casein", "pea protein", "soy protein", "soy isolate",
    "milk protein", "egg white", "hemp protein", "collagen",
    "chickpea", "lentil", "quinoa", "almonds", "cashews", "peanut",
]


# ── Helper functions (identical logic to notebook) ────────────────────────────
def _assign_category(tags: str) -> str:
    if not isinstance(tags, str) or not tags.strip():
        return OTHER
    tl = tags.lower()
    for cat, kws in CATEGORY_MAP.items():
        if any(kw in tl for kw in kws):
            return cat
    return OTHER


def _compute_hsi(df: pd.DataFrame) -> pd.Series:
    def minmax(s):
        rng = s.max() - s.min()
        return (s - s.min()) / (rng if rng > 0 else 1.0)
    return (
        minmax(df["proteins_100g"]) * 0.35
        + minmax(df["fiber_100g"])  * 0.30
        - minmax(df["sugars_100g"]) * 0.25
        - minmax(df["fat_100g"])    * 0.10
    )


# ── Data loading ──────────────────────────────────────────────────────────────
@st.cache_data(show_spinner="Loading data — this takes ~2 min on first run...")
def load_data() -> pd.DataFrame:
    # Fast path: local summary CSV generated by the notebook
    try:
        df = pd.read_csv("sugar_trap_summary.csv")
        if "health_score" not in df.columns:
            df["health_score"] = _compute_hsi(df)
        return df
    except FileNotFoundError:
        pass

    # Slow path: download from OpenFoodFacts (capped at 100k rows for Streamlit Cloud)
    try:
        df_raw = pd.read_csv(
            DATA_URL,
            usecols=RELEVANT_COLS,
            nrows=100_000,
            low_memory=False,
            sep="\t",
            on_bad_lines="skip",
        )
    except Exception as e:
        st.error(f"Failed to load data from OpenFoodFacts: {e}")
        st.stop()

    required = ["product_name", "sugars_100g", "proteins_100g"]
    df = df_raw.dropna(subset=required).copy()
    for col in ["sugars_100g", "proteins_100g", "fat_100g", "fiber_100g"]:
        if col in df.columns:
            df = df[df[col].between(0, 100)]
    for col in ["fat_100g", "fiber_100g", "energy_100g"]:
        if col in df.columns:
            df[col] = df[col].fillna(df[col].median())
    df = df.drop_duplicates(subset="product_name", keep="first")
    df["primary_category"] = df["categories_tags"].apply(_assign_category)
    df["health_score"] = _compute_hsi(df)
    return df


df = load_data()

